const FAQS_STORAGE_KEY = 'dyadia_faqs_v3';

export const faqService = {
  async getFAQs(): Promise<FAQItem[]> {
    try {
      const res = await fetch('/api/faqs');
      if (res.ok) {
        const json = await res.json();
        if (json.success && Array.isArray(json.data) && json.data.length > 0) {
          localStorage.setItem(FAQS_STORAGE_KEY, JSON.stringify(json.data));
          return json.data;
        }
      }
    } catch {
      // ignore
    }

    try {
      const raw = localStorage.getItem(FAQS_STORAGE_KEY);
      if (raw) {
        const parsed = JSON.parse(raw);
        if (Array.isArray(parsed) && parsed.length > 0) return parsed;
      }
    } catch {
      // ignore
    }

    return INITIAL_FAQS;
  },

  async saveFAQ(faq: FAQItem, token?: string): Promise<boolean> {
    try {
      const res = await fetch(`/api/admin/faqs/${faq.id}`, {
        method: 'PUT',
        headers: {
          'Content-Type': 'application/json',
          'x-admin-key': 'dyadia2026',
          ...(token ? { Authorization: `Bearer ${token}` } : {}),
        },
        body: JSON.stringify(faq),
      });
      if (res.ok) {
        const all = await this.getFAQs();
        const index = all.findIndex((f) => f.id === faq.id);
        const updated = index >= 0 ? all.map((f) => (f.id === faq.id ? faq : f)) : [...all, faq];
        localStorage.setItem(FAQS_STORAGE_KEY, JSON.stringify(updated));
        window.dispatchEvent(new Event('dyadia_faqs_updated'));
        return true;
      }
    } catch {
      // ignore
    }

    const all = await this.getFAQs();
    const index = all.findIndex((f) => f.id === faq.id);
    const updated = index >= 0 ? all.map((f) => (f.id === faq.id ? faq : f)) : [...all, faq];
    localStorage.setItem(FAQS_STORAGE_KEY, JSON.stringify(updated));
    window.dispatchEvent(new Event('dyadia_faqs_updated'));
    return true;
  },

  async deleteFAQ(id: string, token?: string): Promise<boolean> {
    try {
      await fetch(`/api/admin/faqs/${id}`, {
        method: 'DELETE',
        headers: {
          'x-admin-key': 'dyadia2026',
          ...(token ? { Authorization: `Bearer ${token}` } : {}),
        },
      });
    } catch {
      // ignore
    }

    const all = await this.getFAQs();
    const filtered = all.filter((f) => f.id !== id);
    localStorage.setItem(FAQS_STORAGE_KEY, JSON.stringify(filtered));
    window.dispatchEvent(new Event('dyadia_faqs_updated'));
    return true;
  },
};
